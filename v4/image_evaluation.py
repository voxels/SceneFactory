import identity_annotations


EVALUATOR_VERSION = "v4-heldout-image-eval-1"
DEFAULT_NEGATIVE = "extra people, distorted face, duplicate limbs, text, watermark"
DEFAULT_SEEDS = (260801, 260802)
# These prompts are deliberately independent of the training captions.  They
# exercise frontal, three-quarter, profile, and full-body generalisation while
# keeping the seed set fixed across every candidate.
PROMPT_VARIANTS = (
    ("front_studio", "studio portrait, frontal view, neutral expression, natural skin, accurate anatomy"),
    ("three_quarter_editorial", "editorial photograph, left three-quarter view, soft daylight, natural skin, accurate anatomy"),
    ("profile_natural", "natural-light portrait, right profile view, relaxed expression, accurate anatomy"),
    ("full_body_editorial", "editorial photograph, full body, relaxed standing pose, natural proportions, accurate anatomy"),
)


class ImageEvaluationError(RuntimeError):
    """A missing evaluation contract or a failed connected evaluation."""


def _assert_plan_inputs_current(project_root: Path, plan: dict[str, Any]) -> None:
    """Fail closed if a plan's graph or candidate adapter changed after planning."""
    manifest_path = project_root / "build/workflows/image_ablation/manifest.json"
    expected_manifest = plan.get("workflow_manifest_sha256")
    if expected_manifest and manifest_path.is_file():
        actual_manifest = identity.sha256_file(manifest_path)
        if actual_manifest != expected_manifest:
            raise ImageEvaluationError(
                f"workflow manifest changed since evaluation plan: expected {expected_manifest}, got {actual_manifest}"
            )
    for candidate in plan.get("candidates", []):
        adapter_path = candidate.get("adapter_path")
        expected_adapter = candidate.get("adapter_sha256")
        if not adapter_path or not expected_adapter:
            continue
        path = Path(adapter_path)
        if not path.is_file() or identity.sha256_file(path) != expected_adapter:
            raise ImageEvaluationError(
                f"candidate adapter changed since evaluation plan: {path}"
            )


def _acquire_run_lock(run_root: Path):
    """Acquire an exclusive lock so retries cannot double-submit a matrix."""
    run_root.mkdir(parents=True, exist_ok=True)
    handle = (run_root / "evaluator.lock").open("a+")
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except (BlockingIOError, OSError):
        handle.close()
        raise ImageEvaluationError(
            f"held-out evaluator is already running for {run_root.name}"
        )
    return handle


def _acquire_project_lock(project_root: Path):
    """Acquire one evaluator lock for the project, across plan-hash directories."""
    lock_root = project_root.resolve() / "build/training/image_identity/heldout_runs"
    lock_root.mkdir(parents=True, exist_ok=True)
    handle = (lock_root / "evaluator.project.lock").open("a+")
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except (BlockingIOError, OSError):
        handle.close()
        raise ImageEvaluationError("an image evaluator is already running for this project")
    return handle


def _release_run_lock(handle) -> None:
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
    finally:
        handle.close()


def _source_root(project_root: Path, config: dict[str, Any]) -> Path:
    root = (project_root / config["source_root"]).resolve()
    if not root.is_dir():
        raise ImageEvaluationError(f"configured source root is missing: {root}")
    return root


def _heldout_records(project_root: Path) -> list[dict[str, Any]]:
    path = project_root / "build/identity/selection_manifest.json"
    if not path.is_file():
        raise ImageEvaluationError("selection manifest is missing; run process-identity first")
    selection = identity.read_json(path)
    eligible = [item for item in selection.get("selections", []) if item.get("eligible_for_export")]
    records = [item for item in eligible if item.get("split") == "final_test"]
    if not records:
        raise ImageEvaluationError("final_test split has no export-eligible images")
    for item in records:
        source = Path(item.get("path", ""))
        if not source.is_file() or identity.sha256_file(source) != item.get("sha256"):
            raise ImageEvaluationError(f"held-out source is missing or changed: {source}")
    groups = {item.get("group_id") for item in records}
    if None in groups:
        raise ImageEvaluationError("held-out records must carry group_id values")
    train_groups = {item.get("group_id") for item in eligible if item.get("split") in {"train", "validation", "calibration"}}
    if groups & train_groups:
        raise ImageEvaluationError(f"held-out groups leak into training splits: {sorted(groups & train_groups)[:4]}")
    return sorted(records, key=lambda item: item["asset_id"])


def _completed_candidates(project_root: Path) -> list[dict[str, Any]]:
    plan_path = project_root / "build/training/image_identity/training_plan.json"
    manifest_path = project_root / "build/workflows/image_ablation/manifest.json"
    if not plan_path.is_file():
        raise ImageEvaluationError("training plan is missing; complete image training first")
    if not manifest_path.is_file():
        raise ImageEvaluationError("image workflow manifest is missing; compile workflows first")
    plan = identity.read_json(plan_path)
    manifest = identity.read_json(manifest_path)
    route_by_name = {item.get("name"): item for item in manifest.get("routes", [])
                     if isinstance(item, dict)}
    candidates = [{
        "experiment": "baseline",
        "adapter_path": None,
        "adapter_sha256": None,
        "adapter_audit": None,
        "route_names": ["base", "native_reference"],
        "training_marker_sha256": None,
        "promotable": False,
    }]
    for route_name in candidates[0]["route_names"]:
        route = route_by_name.get(route_name)
        if not route or route.get("status") != "compiled":
            raise ImageEvaluationError(f"compiled baseline route is missing: {route_name}")
    pulid = route_by_name.get("pulid")
    if pulid and pulid.get("status") == "compiled" and all(
        comfy_executor._model_exists(name) for name in pulid.get("required_models", [])
    ):
        candidates[0]["route_names"].append("pulid")
    for experiment in sorted(plan.get("experiments", []), key=lambda item: item.get("name", "")):
        name = experiment.get("name")
        marker_path = Path(experiment.get("output_dir", "")) / "experiment_complete.json"
        if not name or not marker_path.is_file():
            raise ImageEvaluationError(f"experiment is not complete: {name}")
        marker = identity.read_json(marker_path)
        adapter_path = Path(experiment["output_dir"]) / "pytorch_lora_weights.safetensors"
        if not adapter_path.is_file():
            raise ImageEvaluationError(f"experiment adapter is missing: {adapter_path}")
        audit = adapter_validation.validate(adapter_path, expected_rank=int(experiment["rank"]))
        if audit.get("status") != "structurally_loadable":
            raise ImageEvaluationError(f"adapter audit did not pass: {adapter_path}")
        adapter_sha = identity.sha256_file(adapter_path)
        declared = next((item for item in marker.get("adapters", [])
                         if item.get("path") == str(adapter_path)), None)
        if declared and declared.get("sha256") != adapter_sha:
            raise ImageEvaluationError(f"adapter hash changed since completion: {adapter_path}")
        route_names = []
        for prefix in ("subject_lora_", "lora_reference_"):
            route_name = prefix + name
            route = route_by_name.get(route_name)
            if not route or route.get("status") != "compiled":
                raise ImageEvaluationError(f"compiled candidate route is missing: {route_name}")
            if route.get("adapter_sha256") != adapter_sha:
                raise ImageEvaluationError(f"route adapter hash does not match experiment: {route_name}")
            graph = Path(route.get("path", ""))
            if not graph.is_file():
                raise ImageEvaluationError(f"candidate graph is missing: {graph}")
            route_names.append(route_name)
        candidates.append({
            "experiment": name,
            "adapter_path": str(adapter_path.resolve()),
            "adapter_sha256": adapter_sha,
            "adapter_audit": audit,
            "route_names": route_names,
            "training_marker_sha256": identity.sha256_file(marker_path),
            "promotable": True,
        })
    if len(candidates) == 1:
        raise ImageEvaluationError("training plan contains no completed candidates")
    return candidates


def build_plan(project_root: Path) -> dict[str, Any]:
    """Create a deterministic held-out evaluation plan without contacting ComfyUI."""
    project_root = project_root.resolve()
    config = identity.read_json(project_root / "identity.json")
    identity.validate_config(config)
    heldout = _heldout_records(project_root)
    candidates = _completed_candidates(project_root)
    manifest_path = project_root / "build/workflows/image_ablation/manifest.json"
    manifest = identity.read_json(manifest_path)
    route_by_name = {item.get("name"): item for item in manifest.get("routes", [])
                     if isinstance(item, dict)}
    trigger = config["identity"]["trigger_token"]
    cases = []
    for variant, suffix in PROMPT_VARIANTS:
        for seed in DEFAULT_SEEDS:
            cases.append({
                "case_id": f"{variant}_seed{seed}",
                "variant": variant,
                "seed": seed,
                "prompt": f"{trigger}, {suffix}",
                "negative_prompt": DEFAULT_NEGATIVE,
            })
    source_root = _source_root(project_root, config)
    anchors = [(source_root / item).resolve() for item in config["identity_matching"]["anchors"]]
    missing = [str(item) for item in anchors if not item.is_file()]
    if missing:
        raise ImageEvaluationError(f"identity anchors are missing: {missing}")
    pulid_route = route_by_name.get("pulid")
    pulid_available = bool(pulid_route and pulid_route.get("status") == "compiled" and
                           all(comfy_executor._model_exists(name) for name in pulid_route.get("required_models", [])))
    plan = {
        "schema_version": 1,
        "status": "planned",
        "evaluator": EVALUATOR_VERSION,
        "identity_id": config["identity"]["id"],
        "selection_manifest_sha256": identity.sha256_file(project_root / "build/identity/selection_manifest.json"),
        "workflow_manifest_sha256": identity.sha256_file(manifest_path),
        "heldout": [{
            "asset_id": item["asset_id"], "path": str(Path(item["path"]).resolve()),
            "sha256": item["sha256"], "group_id": item["group_id"],
            "caption": item.get("caption", {}).get("caption"),
        } for item in heldout],
        "anchors": [{"path": str(item), "sha256": identity.sha256_file(item)} for item in anchors],
        "cases": cases,
        "candidates": candidates,
        "ablations": {
            "base": {"status": "scheduled", "routes": ["base"]},
            "native_reference": {"status": "scheduled", "routes": ["native_reference"]},
            "pulid": {"status": "scheduled" if pulid_available else "unavailable", "route": "pulid",
                       "reason": None if pulid_available else "PuLID checkpoint or required runtime model is unavailable"},
        },
        "contract": {
            "expected_outputs": len(cases),
            "required_metrics": ["identity_feature_print_median_distance", "face_detection_rate", "output_sha256"],
            "promotion": {
                "minimum_face_detection_rate": 0.80,
                "maximum_identity_feature_print_median_distance": float(config["identity_matching"]["maximum_anchor_distance"]),
                "require_all_cases": True,
                "require_unique_winner": True,
            },
            "unsupported_without_additional_model": ["prompt_alignment", "foreground_similarity", "pose_adherence"],
        },
    }
    plan["plan_sha256"] = identity.sha256_bytes(json.dumps(plan, sort_keys=True, separators=(",", ":")).encode())
    output = project_root / "build/training/image_identity/heldout_evaluation_plan.json"
    identity.write_json(output, plan)
    return plan


def _fetch_output(server_url: str, output: dict[str, Any], destination: Path) -> dict[str, Any]:
    filename = str(output.get("filename", ""))
    subfolder = str(output.get("subfolder", ""))
    if (not filename or Path(filename).name != filename or
            Path(subfolder).is_absolute() or ".." in Path(subfolder).parts):
        raise ImageEvaluationError(f"Comfy returned an unsafe output filename: {output}")
    query = urllib.parse.urlencode({
        "filename": filename,
        "subfolder": subfolder,
        "type": str(output.get("type", "output")),
    })
    url = server_url.rstrip("/") + "/view?" + query
    try:
        with urllib.request.urlopen(url, timeout=60) as response:
            data = response.read()
    except (OSError, urllib.error.URLError) as error:
        raise ImageEvaluationError(f"failed to download Comfy output {filename}: {error}") from error
    if len(data) < 16 or not (data.startswith(b"\x89PNG\r\n\x1a\n") or data.startswith(b"\xff\xd8\xff")):
        raise ImageEvaluationError(f"Comfy output is empty, truncated, or not an image: {filename}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(data)
    return {"path": str(destination), "sha256": identity.sha256_file(destination), "bytes": len(data), "source": output}


def _ensure_isolator(project_root: Path) -> Path:
    """Return the pinned Vision isolator, compiling it if the binary is absent."""
    binary = project_root / "build/bin/k-identity-isolator"
    source = Path(__file__).resolve().parent.parent / "v3/tools/k_identity_isolator.swift"
    if not source.is_file():
        raise ImageEvaluationError(f"identity metric source is missing: {source}")
    if not binary.is_file():
        try:
            identity_annotations.compile_swift(source, binary, ["AppKit", "CoreImage", "Vision"])
        except (OSError, subprocess.CalledProcessError) as error:
            raise ImageEvaluationError(f"Apple Vision identity metric runtime is unavailable: {error}") from error
    return binary


def _score_outputs(project_root: Path, plan: dict[str, Any], output_records: list[dict[str, Any]], run_root: Path) -> list[dict[str, Any]]:
    if len(output_records) != len(plan["cases"]):
        raise ImageEvaluationError("candidate output count does not match the fixed evaluation plan")
    isolator = _ensure_isolator(project_root)
    config = identity.read_json(project_root / "identity.json")
    source_root = _source_root(project_root, config)
    metric_root = run_root / "vision_metrics"
    metric_config = metric_root / "isolation_config.json"
    metric_sources = [item["artifact"]["path"] for item in output_records]
    metric_config.parent.mkdir(parents=True, exist_ok=True)
    identity.write_json(metric_config, {
        "identity_id": plan["identity_id"],
        "anchors": [str((source_root / item).resolve()) for item in config["identity_matching"]["anchors"]],
        "sources": metric_sources,
        "output_root": str(metric_root / "isolation"),
        "manual_face_overrides": {}, "manual_person_overrides": {}, "reject_person_isolation": [],
    })
    try:
        subprocess.run([str(isolator), str(metric_config)], check=True, capture_output=True, text=True)
    except (OSError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", "")
        raise ImageEvaluationError(f"Apple Vision identity scoring failed: {detail[-1200:]}") from error
    report_path = metric_root / "isolation/isolation_report.json"
    if not report_path.is_file():
        raise ImageEvaluationError("identity scorer emitted no isolation report")
    report = identity.read_json(report_path)
    by_path = {str(Path(item["source_path"]).resolve()): item for item in report.get("records", [])}
    scored = []
    for item in output_records:
        path = str(Path(item["artifact"]["path"]).resolve())
        record = by_path.get(path)
        if not record:
            raise ImageEvaluationError(f"identity scorer omitted output: {path}")
        faces = [face for face in record.get("faces", []) if face.get("median_distance") is not None]
        best = min(faces, key=lambda face: float(face["median_distance"])) if faces else None
        scored.append({
            "case_id": item["case_id"], "seed": item["seed"], "path": path,
            "sha256": item["artifact"]["sha256"], "bytes": item["artifact"]["bytes"],
            "identity_feature_print_median_distance": best.get("median_distance") if best else None,
            "face_detected": bool(record.get("faces")),
            "face_count": len(record.get("faces", [])),
            "face_area_fraction": ((best["box"]["width"] * best["box"]["height"]) if best else None),
            "person_mask_detected": bool(record.get("mask_path")),
            "vision_record_status": record.get("status"),
            "runtime_seconds": item.get("execution", {}).get("elapsed_seconds"),
        })
    return scored


def _candidate_summary(metrics: list[dict[str, Any]]) -> dict[str, Any]:
    distances = [float(item["identity_feature_print_median_distance"]) for item in metrics
                 if item.get("identity_feature_print_median_distance") is not None]
    runtimes = [float(item["runtime_seconds"]) for item in metrics
                if item.get("runtime_seconds") is not None]
    return {
        "case_count": len(metrics),
        "identity_scored_cases": len(distances),
        "identity_feature_print_median_distance": statistics.median(distances) if distances else None,
        "face_detection_rate": (sum(bool(item.get("face_detected")) for item in metrics) / len(metrics)) if metrics else 0.0,
        "person_mask_rate": (sum(bool(item.get("person_mask_detected")) for item in metrics) / len(metrics)) if metrics else 0.0,
        "all_output_hashes_present": all(bool(item.get("sha256")) for item in metrics),
        "runtime_seconds_median": statistics.median(runtimes) if runtimes else None,
    }


def _promotion_eligibility(summary: dict[str, Any], plan: dict[str, Any]) -> list[str]:
    policy = plan["contract"]["promotion"]
    blockers = []
    if summary["case_count"] != plan["contract"]["expected_outputs"]:
        blockers.append("not all fixed cases produced an output")
    if summary["identity_scored_cases"] != summary["case_count"]:
        blockers.append("one or more outputs has no usable identity feature print")
    if summary["face_detection_rate"] < policy["minimum_face_detection_rate"]:
        blockers.append("face detection rate is below promotion threshold")
    distance = summary["identity_feature_print_median_distance"]
    if distance is None or distance > policy["maximum_identity_feature_print_median_distance"]:
        blockers.append("identity feature-print distance is above promotion threshold")
    if not summary["all_output_hashes_present"]:
        blockers.append("one or more output hashes is missing")
    return blockers


def _evaluate_impl(project_root: Path, *, server_url: str = "http://127.0.0.1:8188",
                   timeout_seconds: int = 3600, poll_seconds: float = 2.0,
                   _plan: dict[str, Any] | None = None,
                   _run_root: Path | None = None) -> dict[str, Any]:
    """Generate and score every candidate route; promote only a unique eligible winner."""
    project_root = project_root.resolve()
    plan = _plan or build_plan(project_root)
    _assert_plan_inputs_current(project_root, plan)
    run_root = _run_root or (project_root / "build/training/image_identity/heldout_runs" / plan["plan_sha256"][:16])
    report_path = run_root / "evaluation_report.json"
    existing = identity.read_json(report_path) if report_path.is_file() else None
    # Completed runs are immutable.  Running/blocked reports are deliberately
    # resumable after a client or backend interruption: preserve their
    # hash-verified cases and continue at the first missing case.  The per-run
    # kernel lock prevents two evaluators from mutating this same report.
    if (existing and existing.get("plan_sha256") == plan["plan_sha256"]
            and existing.get("status") == "complete"):
        return existing
    if (existing and existing.get("status") in {"running", "blocked"}
            and existing.get("plan_sha256") not in {None, plan["plan_sha256"]}):
        # A changed workflow/model/selection hash means the old resumable report
        # no longer describes the current graph. Preserve it as historical
        # evidence instead of silently mixing outputs from two plans.
        raise ImageEvaluationError(
            f"existing evaluation report plan hash {existing.get('plan_sha256')} "
            f"differs from current plan {plan['plan_sha256']}; start a new held-out run"
        )
    if (existing and existing.get("plan_sha256") == plan["plan_sha256"]
            and existing.get("status") in {"running", "blocked"}):
        report = existing
        report["status"] = "running"
        report.pop("blockers", None)
        report["resume_count"] = int(report.get("resume_count", 0)) + 1
        report.setdefault("candidates", [])
    else:
        report = {
            "schema_version": 1, "status": "running", "evaluator": EVALUATOR_VERSION,
            "plan_sha256": plan["plan_sha256"], "server": server_url.rstrip("/"),
            "candidates": [], "resume_count": 0,
        }
    # An interrupted client may leave an advisory active-case marker behind;
    # the kernel lock proves no other evaluator is alive before we clear it.
    for candidate_result in report.get("candidates", []):
        for route_result in candidate_result.get("routes", []):
            route_result.pop("active_case", None)
    identity.write_json(report_path, report)
    try:
        # Persist the candidate/route/case structure before each expensive call.
        # A ComfyUI crash therefore leaves a resumable report instead of forcing
        # already completed generations to be repeated.
        for candidate in plan["candidates"]:
            _assert_plan_inputs_current(project_root, {"candidates": [candidate]})
            candidate_result = next((item for item in report["candidates"]
                                     if item.get("experiment") == candidate["experiment"]), None)
            if candidate_result is None:
                candidate_result = {"experiment": candidate["experiment"], "adapter_sha256": candidate["adapter_sha256"],
                                    "promotable": bool(candidate.get("promotable")), "routes": []}
                report["candidates"].append(candidate_result)
                identity.write_json(report_path, report)
            for route_name in candidate["route_names"]:
                route_result = next((item for item in candidate_result["routes"]
                                     if item.get("route") == route_name), None)
                if route_result is None:
                    route_result = {"route": route_name, "cases": []}
                    candidate_result["routes"].append(route_result)
                    identity.write_json(report_path, report)
                completed_cases = {item.get("case_id") for item in route_result["cases"]}
                for case in plan["cases"]:
                    if case["case_id"] in completed_cases:
                        continue
                    route_result["active_case"] = {
                        "case_id": case["case_id"],
                        "started_at_unix": time.time(),
                    }
                    identity.write_json(report_path, report)
                    result = comfy_executor.execute(
                        project_root, route_name, server_url=server_url,
                        timeout_seconds=timeout_seconds, poll_seconds=poll_seconds,
                        prompt_override=case["prompt"], negative_prompt_override=case["negative_prompt"],
                        seed=case["seed"], filename_prefix=f"sfv4_eval_{candidate['experiment']}_{case['case_id']}",
                    )
                    outputs = result.get("outputs", [])
                    if len(outputs) != 1:
                        raise ImageEvaluationError(f"route {route_name} returned {len(outputs)} outputs for {case['case_id']}")
                    destination = run_root / candidate["experiment"] / route_name / f"{case['case_id']}.png"
                    artifact = _fetch_output(server_url, outputs[0], destination)
                    route_result["cases"].append({"case_id": case["case_id"], "seed": case["seed"], "prompt": case["prompt"], "execution": result, "artifact": artifact})
                    route_result.pop("active_case", None)
                    identity.write_json(report_path, report)
                if len(route_result["cases"]) < len(plan["cases"]):
                    raise ImageEvaluationError(f"route {route_name} has incomplete fixed-case outputs")
                route_result["metrics"] = _score_outputs(project_root, plan, route_result["cases"], run_root / candidate["experiment"] / route_name)
                route_result["summary"] = _candidate_summary(route_result["metrics"])
                route_result["promotion_blockers"] = _promotion_eligibility(route_result["summary"], plan)
                identity.write_json(report_path, report)
    except (comfy_executor.ComfyExecutionError, ImageEvaluationError, OSError, ValueError) as error:
        report["status"] = "blocked"
        report["blockers"] = [str(error)]
        identity.write_json(report_path, report)
        raise ImageEvaluationError(str(error)) from error

    baseline_routes = {
        route.get("route"): route for candidate in report["candidates"]
        if candidate.get("experiment") == "baseline" for route in candidate.get("routes", [])
    }
    if not {"base", "native_reference"}.issubset(baseline_routes):
        report["status"] = "blocked"
        report["blockers"] = ["base/native-reference baseline routes are missing"]
        identity.write_json(report_path, report)
        raise ImageEvaluationError(report["blockers"][0])
    baseline_distances = [
        float(route["summary"]["identity_feature_print_median_distance"])
        for route in baseline_routes.values()
        if route.get("summary", {}).get("identity_feature_print_median_distance") is not None
    ]
    if not baseline_distances:
        report["status"] = "blocked"
        report["blockers"] = ["base/native-reference baseline metrics are missing"]
        identity.write_json(report_path, report)
        raise ImageEvaluationError(report["blockers"][0])
    baseline_best = min(baseline_distances)
    eligible = [route for candidate in report["candidates"]
                for route in candidate["routes"]
                if candidate.get("promotable") and not route["promotion_blockers"]
                and float(route["summary"]["identity_feature_print_median_distance"]) < baseline_best]
    # Sort on measured identity distance, then detection rate.  A tie at the
    # full measured precision is intentionally not promoted automatically.
    eligible.sort(key=lambda route: (
        float(route["summary"]["identity_feature_print_median_distance"]),
        -float(route["summary"]["face_detection_rate"]),
    ))
    if not eligible:
        report["status"] = "blocked"
        report["blockers"] = ["no candidate improved identity distance over the base/native-reference baseline"]
        identity.write_json(report_path, report)
        raise ImageEvaluationError(report["blockers"][0])
    if len(eligible) > 1 and eligible[0]["summary"] == eligible[1]["summary"]:
        report["status"] = "blocked"
        report["blockers"] = ["held-out winner is not unique at measured precision"]
        identity.write_json(report_path, report)
        raise ImageEvaluationError(report["blockers"][0])
    winner = eligible[0]
    winner_candidate = next(item for item in report["candidates"] if winner in item["routes"])
    source = Path(next(item for item in plan["candidates"] if item["experiment"] == winner_candidate["experiment"])["adapter_path"])
    promotion_root = project_root / "build/training/image_identity/promoted"
    destination = promotion_root / "pytorch_lora_weights.safetensors"
    promotion_root.mkdir(parents=True, exist_ok=True)
    if destination.is_file() and identity.sha256_file(destination) != identity.sha256_file(source):
        raise ImageEvaluationError(f"promoted adapter collision: {destination}")
    if not destination.exists():
        destination.write_bytes(source.read_bytes())
    promotion = {
        "schema_version": 1, "status": "promoted", "evaluator": EVALUATOR_VERSION,
        "plan_sha256": plan["plan_sha256"], "experiment": winner_candidate["experiment"],
        "route": winner["route"], "source": str(source), "source_sha256": identity.sha256_file(source),
        "path": str(destination), "sha256": identity.sha256_file(destination),
        "summary": winner["summary"], "graph_sha256": next(item for item in identity.read_json(project_root / "build/workflows/image_ablation/manifest.json")["routes"] if item.get("name") == winner["route"])["graph_sha256"],
        "metrics_path": str(report_path),
    }
    adapter_validation.validate(destination, expected_rank=int(next(item for item in plan["candidates"] if item["experiment"] == winner_candidate["experiment"])["adapter_audit"]["declared_rank"]))
    identity.write_json(promotion_root / "promotion_manifest.json", promotion)
    report.update({"status": "complete", "winner": promotion})
    identity.write_json(report_path, report)
    plan["status"] = "evaluated_and_promoted"
    plan["winner"] = promotion
    identity.write_json(project_root / "build/training/image_identity/heldout_evaluation_plan.json", plan)
    training_plan_path = project_root / "build/training/image_identity/training_plan.json"
    training_plan = identity.read_json(training_plan_path)
    training_plan["status"] = "image_identity_promoted"
    training_plan["promotion"] = promotion
    identity.write_json(training_plan_path, training_plan)
    return report


def evaluate(project_root: Path, *, server_url: str = "http://127.0.0.1:8188",
             timeout_seconds: int = 3600, poll_seconds: float = 2.0) -> dict[str, Any]:
    """Run one locked, resumable held-out evaluation."""
    project_root = project_root.resolve()
    plan = build_plan(project_root)
    run_root = project_root / "build/training/image_identity/heldout_runs" / plan["plan_sha256"][:16]
    project_lock = _acquire_project_lock(project_root)
    try:
        lock = _acquire_run_lock(run_root)
        try:
            return _evaluate_impl(project_root, server_url=server_url,
                                  timeout_seconds=timeout_seconds,
                                  poll_seconds=poll_seconds,
                                  _plan=plan, _run_root=run_root)
        finally:
            _release_run_lock(lock)
    finally:
        _release_run_lock(project_lock)
