#!/usr/bin/env python3
"""Run a fixed, auditable held-out bakeoff for trained image identity adapters.

This module is intentionally conservative.  It never invents an image, metric,
or winner: every candidate case must be generated by the connected ComfyUI API,
downloaded, hashed, and scored by the same Apple Vision feature-print matcher
used during source selection before promotion is allowed.
"""

